#!/usr/bin/env node
// The Queryable declarations of @lambdaorm/base (its build) as globals for Monaco: no imports (what they bring is
// `any`), no `export`. Written into src/infrastructure/monaco/queryableDeclarations.generated.ts, committed, and
// regenerated on every build so the editor knows the clauses and functions of the λORM version in the repo.
import { readFileSync, writeFileSync, existsSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'

const here = dirname(fileURLToPath(import.meta.url))
const source = join(here, '../../base/build/lib/repository/domain/queryable.d.ts')
const target = join(here, '../src/infrastructure/monaco/queryableDeclarations.generated.ts')
if (!existsSync(source)) {
	console.warn(`${source} not found (build @lambdaorm/base first): keeping the committed declarations`)
	process.exit(0)
}
const text = readFileSync(source, 'utf8')
const imported = [...text.matchAll(/^import \{([^}]+)\} from .*$/gm)].flatMap(m => m[1].split(',').map(s => s.trim()).filter(Boolean))
const declarations = imported.map(name => `type ${name} = any`).join('\n') + '\n' +
	text.replace(/^import .*$/gm, '').replace(/^export declare /gm, 'declare ').replace(/^export /gm, '').replace(/\n{3,}/g, '\n\n')
writeFileSync(target, `// generated by scripts/queryableDeclarations.mjs from @lambdaorm/base: do not edit\n/* eslint-disable */\nexport const QUERYABLE_DECLARATIONS = ${JSON.stringify(declarations)}\n`)
console.log(`✓ ${target}`)
