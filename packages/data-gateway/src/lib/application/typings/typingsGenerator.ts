import { DomainSchema, Entity } from '@lambdaorm/base'

/** Same names as the model generator of the CLI (packages/cli, languages/node.ts): Qry + singular in PascalCase */
const singular = (word: string): string => {
	if (/ies$/i.test(word)) return word.replace(/ies$/i, 'y')
	if (/(ss|us|is)$/i.test(word)) return word
	if (/(ses|xes|zes|ches|shes)$/i.test(word)) return word.replace(/es$/i, '')
	if (/s$/i.test(word)) return word.replace(/s$/i, '')
	return word
}

const pascal = (text: string): string => text.split(/[^a-zA-Z0-9]+/).filter(Boolean).map(w => w[0].toUpperCase() + w.slice(1)).join('')

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/

export const queryInterfaceName = (entity: Entity): string => `Qry${pascal(entity.singular ?? singular(entity.name))}`

const tsType = (type: string | undefined): string => {
	switch (type) {
	case 'integer': case 'decimal': case 'number': return 'number'
	case 'dateTime': case 'date': case 'time': return 'Date'
	case 'boolean': return 'boolean'
	case 'object': return 'any'
	case 'any': return 'any'
	default: return 'string'
	}
}

const key = (name: string): string => IDENTIFIER.test(name) ? name : JSON.stringify(name)

/**
 * The domain of a schema as TypeScript declarations for an editor (Monaco), equivalent to the __queryable.d.ts of the
 * CLI: an interface Qry<Entity> per entity (properties and relations, `ManyToOne` for lists as λORM names them) and a
 * global per root entity (`declare const Orders: Queryable<QryOrder> & { details: Queryable<QryOrderDetail> }` for
 * the nested `Orders.details`). Queryable, the relation types and the functions are declared apart (base).
 */
export const generateTypings = (domain: DomainSchema): string => {
	const entities = domain.entities ?? []
	const byName = new Map(entities.map(e => [e.name, e]))
	const lines: string[] = ['// generated by the data-gateway from the domain of the schema', '']
	for (const e of domain.enums ?? []) {
		lines.push(`declare enum ${pascal(e.name)} {`)
		lines.push(e.values.map(v => `\t${key(v.name)} = ${typeof v.value === 'number' ? v.value : JSON.stringify(String(v.value))}`).join(',\n'))
		lines.push('}', '')
	}
	for (const entity of entities) {
		const name = queryInterfaceName(entity)
		const parent = entity.extends && byName.get(entity.extends) ? ` extends ${queryInterfaceName(byName.get(entity.extends)!)}` : ''
		lines.push(`interface ${name}${parent} {`)
		for (const property of entity.properties ?? []) {
			lines.push(`\t${key(property.name)}: ${property.enum ? pascal(property.enum) : tsType(property.type)}`)
		}
		for (const relation of entity.relations ?? []) {
			const target = byName.get(relation.entity)
			if (!target) continue
			const qry = queryInterfaceName(target)
			// λORM names the type from the other side: manyToOne is a list (Orders.details), oneToMany one row
			if (relation.type === 'manyToOne') lines.push(`\t${key(relation.name)}: ManyToOne<${qry}>`)
			else if (relation.type === 'oneToOne') lines.push(`\t${key(relation.name)}: ${qry} & OneToOne<${qry}>`)
			else lines.push(`\t${key(relation.name)}: ${qry} & OneToMany<${qry}>`)
		}
		lines.push('}', '')
	}
	// roots, with their nested entities ("Orders.details") as properties
	const roots = entities.filter(e => !e.abstract && !e.name.includes('.'))
	for (const root of roots) {
		const nested = entities.filter(e => !e.abstract && e.name.startsWith(`${root.name}.`) && !e.name.slice(root.name.length + 1).includes('.'))
		const children = nested.map(child => `${key(child.name.slice(root.name.length + 1))}: Queryable<${queryInterfaceName(child)}>`)
		const type = `Queryable<${queryInterfaceName(root)}>${children.length ? ` & { ${children.join('; ')} }` : ''}`
		if (IDENTIFIER.test(root.name)) lines.push(`declare const ${root.name}: ${type}`)
	}
	return lines.join('\n') + '\n'
}
